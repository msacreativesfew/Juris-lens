import React, { useState } from 'react';
import { X, Copy, Check, Printer, FileText } from 'lucide-react';
import { ComplianceReport } from '../types/compliance';

interface ExecutiveBriefModalProps {
  report: ComplianceReport;
  isOpen: boolean;
  onClose: () => void;
}

export const ExecutiveBriefModal: React.FC<ExecutiveBriefModalProps> = ({
  report,
  isOpen,
  onClose,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const generateMarkdownBrief = () => {
    return `# JURISLENS REGULATORY COMPLIANCE AUDIT BRIEF
Asset: ${report.assetName}
Target Jurisdiction: ${report.jurisdiction}
Analysis Timestamp: ${report.analyzedAt}
Evaluation Mode: ${report.analysisMode}

## EXECUTIVE SUMMARY
${report.summary.executiveSummary}

## AUDIT METRICS
- Total Inspected Findings: ${report.summary.totalFindings}
- Potential Issues: ${report.summary.highSeverityCount}
- Review Items: ${report.summary.mediumSeverityCount}
- Verified Compliant: ${report.summary.infoCount}

## TOP PRIORITY REMEDIATION ACTIONS
${report.summary.topActionItems.map((item, idx) => `${idx + 1}. ${item}`).join('\n')}

## STATUTORY FINDINGS DETAILS
${report.findings
  .map(
    (f) => `
### [${f.id}] ${f.title} (${f.severity.toUpperCase()})
- Status: ${f.status}
- Observed Evidence: "${f.observation}"
- Legal Issue: ${f.explanation}
- Statutory Provision: ${f.source.provision} (${f.source.authority})
- Source URL: ${f.source.sourceUrl}
- Recommended Next Step: ${f.recommendation}
${f.suggestedWording ? `- Proposed Compliant Text: "${f.suggestedWording}"` : ''}
`
  )
  .join('\n')}

---
Disclaimer: Generated by JurisLens visual regulatory intelligence workspace. For formal customs clearances, consult registered Singapore regulatory counsel.
`;
  };

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(generateMarkdownBrief());
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-[#26352D]/40 backdrop-blur-xs">
      <div className="relative w-full max-w-3xl max-h-[85vh] flex flex-col rounded-2xl bg-[#FFFEFA] border border-[#DFDACD] shadow-xl overflow-hidden text-[#26352D]">
        {/* Modal Header */}
        <div className="flex items-center justify-between px-6 py-4 border-b border-[#DFDACD] bg-[#FFFEFA]">
          <div className="flex items-center gap-2.5">
            <div className="p-2 rounded-lg bg-[#E5EFE5] text-[#477A58]">
              <FileText className="h-5 w-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-[#26352D]">Compliance Audit Brief</h3>
              <p className="text-xs text-[#68736A]">{report.assetName} · {report.jurisdiction}</p>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={handleCopyMarkdown}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[#FFFEFA] hover:bg-[#F1EEE4] border border-[#DFDACD] text-xs font-semibold text-[#26352D] transition-colors shadow-2xs"
            >
              {copied ? <Check className="h-3.5 w-3.5 text-[#28734A]" /> : <Copy className="h-3.5 w-3.5 text-[#477A58]" />}
              <span>{copied ? 'Copied' : 'Copy Brief'}</span>
            </button>
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-[#477A58] hover:bg-[#386849] text-white text-xs font-semibold transition-colors shadow-xs"
            >
              <Printer className="h-3.5 w-3.5" />
              <span>Print / PDF</span>
            </button>
            <button
              onClick={onClose}
              className="p-1.5 rounded-lg text-[#68736A] hover:text-[#26352D] hover:bg-[#F1EEE4] transition-colors ml-2"
            >
              <X className="h-5 w-5" />
            </button>
          </div>
        </div>

        {/* Modal Content */}
        <div className="flex-1 overflow-y-auto p-6 space-y-6 text-xs leading-relaxed">
          {/* Executive Summary Card */}
          <div className="p-4 rounded-xl bg-[#F1EEE4] border border-[#DFDACD]">
            <h4 className="text-xs font-bold uppercase tracking-wider text-[#477A58] mb-1.5">
              Executive Audit Summary
            </h4>
            <p className="text-[#26352D]">{report.summary.executiveSummary}</p>
          </div>

          {/* Top Priority Action Items */}
          <div className="space-y-2">
            <h4 className="text-xs font-bold uppercase tracking-wider text-[#26352D]">
              Priority Remediation Actions Required:
            </h4>
            <div className="space-y-1.5">
              {report.summary.topActionItems.map((action, i) => (
                <div key={i} className="flex items-start gap-2.5 p-2.5 rounded-lg bg-[#FFFEFA] border border-[#DFDACD]">
                  <span className="font-mono font-bold text-[#477A58] text-xs shrink-0">0{i + 1}.</span>
                  <span className="text-[#26352D]">{action}</span>
                </div>
              ))}
            </div>
          </div>

          {/* Findings Table */}
          <div className="space-y-3">
            <h4 className="text-xs font-bold uppercase tracking-wider text-[#26352D]">
              Itemized Statutory Findings ({report.findings.length})
            </h4>

            <div className="space-y-2">
              {report.findings.map((f) => (
                <div key={f.id} className="p-3 rounded-lg bg-[#F7F5EE] border border-[#DFDACD] space-y-1.5">
                  <div className="flex items-center justify-between">
                    <span className="font-mono font-bold text-[#26352D]">{f.id}</span>
                    <span className={`px-2 py-0.5 rounded text-[10px] font-semibold ${
                      f.severity === 'high'
                        ? 'bg-[#F8E6E8] text-[#B53D4A] border border-[#B53D4A]/20'
                        : f.severity === 'medium'
                        ? 'bg-[#FBF0D2] text-[#8A6417] border border-[#8A6417]/20'
                        : 'bg-[#E5F3E8] text-[#28734A] border border-[#28734A]/20'
                    }`}>
                      {f.severity === 'high' ? 'Potential issue' : f.severity === 'medium' ? 'Needs review' : 'No issue in region'}
                    </span>
                  </div>
                  <div className="text-[#26352D] font-medium">{f.title}</div>
                  <div className="text-[#68736A] text-[11px]">
                    <strong>Observed:</strong> "{f.observation}"
                  </div>
                  <div className="text-[#68736A] text-[11px]">
                    <strong>Statute:</strong> {f.source.provision} ({f.source.authority})
                  </div>
                  {f.suggestedWording && (
                    <div className="p-2 rounded bg-[#FFFEFA] font-mono text-[10px] text-[#26352D] border border-[#DFDACD] mt-1">
                      Proposed Labeling: {f.suggestedWording}
                    </div>
                  )}
                </div>
              ))}
            </div>
          </div>
        </div>
      </div>
    </div>
  );
};
